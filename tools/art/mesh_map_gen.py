#!/usr/bin/env python3
"""Batch species->source-mesh mapping for render_src_asset.py.

Reads tools/species_dump.json, assigns each species a licensed source mesh
by body archetype, derives per-material colors from the species base color,
and writes mesh_cfg_gen.py (generated — do not hand-edit; re-run this).

Hand-tuned entries already in render_src_asset.CFG win: the generated table
only fills species that have no explicit entry.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
DUMP = os.path.join(HERE, "..", "species_dump.json")
OUT = os.path.join(HERE, "mesh_cfg_gen.py")

# species with hand-tuned CFG entries in render_src_asset.py — never emit
HAND = {"fenjelly", "scalcrest", "scalfang", "branpurr", "tidscale",
        "piplump", "digsnout", "dozantler", "cindpaw"}

# identity-mark species — the mesh path has no accessory layer yet, so they
# stay on the primitive renderer where marks render and smoke pins verify.
# (scalcrest/tidscale are in HAND with hand-accepted mark loss — documented.)
import rig_auto
ACCESSORY_SIDS = set(rig_auto.ACCESSORY) - HAND

VOL2 = "animal_pack2/Animal Pack Vol.2 by @Quaternius/Blends/"
FARM = "farm_animals/Farm Animals by @Quaternius/Blends/"

# body -> (blend, head_bone, target_h, mat_map builder)
# builder(c, dark, lite) returns {material_name: (r,g,b)}
TEMPLATES = {
    "bird": (VOL2 + "Eagle.blend", "Bone.003", 1.35,
             lambda c, dark, lite: {"Wings": c, "Head": lite,
                                    "Beak": (0.90, 0.72, 0.30),
                                    "Claws": (0.28, 0.24, 0.30)}),
    "quadruped": (VOL2 + "Wolf.blend", "Bone.003", 1.45,
                  lambda c, dark, lite: {"Wolf": c}),
    "mouse": (VOL2 + "Wolf.blend", "Bone.003", 0.85,
              lambda c, dark, lite: {"Wolf": c}),
    "kitty": (VOL2 + "Cat.blend", "Bone.003", 1.20,
              lambda c, dark, lite: {"Grey": c, "White": lite,
                                     "Pink": (0.95, 0.62, 0.66)}),
    "cow": (FARM + "Cow.blend", "Head", 1.5,
            lambda c, dark, lite: {"White": c, "Black": dark,
                                   "Pink": (0.95, 0.62, 0.66)}),
    "deer": (FARM + "Horse.blend", "Head", 1.55,
             lambda c, dark, lite: {"Material.003": c, "Material.006": dark}),
    "boar": (FARM + "Pig.blend", "Head", 1.30,
             lambda c, dark, lite: {"Material.003": dark, "Material": c}),
    "serpent": (VOL2 + "Piranha.blend", "Bone", 0.80,
                lambda c, dark, lite: {"Brown": c, "LightYellow": lite,
                                       "Black": dark, "White": (0.92, 0.92, 0.88)}),
}

# bodies with no fitting source mesh stay on the primitive fallback path


def hex2rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))


def shade(c, f):
    return tuple(min(1.0, max(0.0, v * f)) for v in c)


def main():
    species = json.load(open(DUMP))
    out = ["# generated by mesh_map_gen.py — do not hand-edit", "CFG_EXT = {"]
    n = 0
    for d in species:
        sid = d.get("id", "")
        body = d.get("body", "")
        if sid in HAND or sid in ACCESSORY_SIDS or body not in TEMPLATES:
            continue
        blend, head_bone, th, mk = TEMPLATES[body]
        c = hex2rgb(d["color"])
        mats = mk(c, shade(c, 0.45), shade(c, 1.25))
        rot = 285.0 if body == "bird" else (-90.0 if body == "serpent" else 0.0)
        mats_s = "{" + ", ".join(
            '"%s": (%.3f, %.3f, %.3f)' % (k, *v) for k, v in mats.items()) + "}"
        eye_fwd = 0.10 if body == "serpent" else (-0.14 if body == "deer" else -0.12)
        nose = ('"nose_r": 0.045, "nose_up": 0.02, ' if body in
                ("quadruped", "kitty", "cow", "deer", "boar", "mouse") else '')
        entry = (f'    "{sid}": {{"blend": "{blend}", "mat_map": {mats_s}, {nose}\n'
                 f'        "head_bone": "{head_bone}", "rot_z": {rot},\n'
                 f'        "action": "Idle", "frames": (5, 25),\n'
                 f'        "eye_r": 0.05, "eye_gap": 0.11, '
                 f'"eye_fwd": {eye_fwd}, "eye_up": 0.10, "target_h": {th},\n'
                 f'        "subd_wool": 2, "displace": None}},')
        out.append(entry)
        n += 1
    out.append("}")
    open(OUT, "w").write("\n".join(out) + "\n")
    print("wrote %d entries -> %s" % (n, OUT))


if __name__ == "__main__":
    main()
