#!/usr/bin/env python3
"""Batch species->source-mesh mapping for render_src_asset.py.

Reads tools/species_dump.json, assigns each species a licensed source mesh
by body archetype, derives per-material colors from the species base color,
and writes mesh_cfg_gen.py (generated — do not hand-edit; re-run this).

Hand-tuned entries already in render_src_asset.CFG win: the generated table
only fills species that have no explicit entry.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
DUMP = os.path.join(HERE, "..", "species_dump.json")
OUT = os.path.join(HERE, "mesh_cfg_gen.py")

# species with hand-tuned CFG entries in render_src_asset.py — never emit
HAND = {"fenjelly", "scalcrest", "scalfang", "branpurr", "tidscale",
        "piplump", "digsnout", "dozantler", "cindpaw",
        "gloamwing", "cragmaw", "hexfiend", "dreadwyrm"}

# identity-mark species — render_src_asset.py's accessory layer rebuilds the
# marks the source meshes lack (crown/halo/horns/crest/fins/mask/wings), so
# they migrate with everyone else. The kind is passed through per species.
import rig_auto

VOL2 = "animal_pack2/Animal Pack Vol.2 by @Quaternius/Blends/"
FARM = "farm_animals/Farm Animals by @Quaternius/Blends/"
CUTE = "cute_monsters/Cute Animated Monsters - Aug 2020/Blends/"
MBASIC = "monsters_basic/Animated Monster Pack by @Quaternius/Blend/"

# body -> (blend, head_bone, target_h, mat_map builder)
# builder(c, dark, lite) returns {material_name: (r,g,b)}
TEMPLATES = {
    "bird": (VOL2 + "Eagle.blend", "Bone.003", 1.35,
             lambda c, dark, lite: {"Wings": c, "Head": lite,
                                    "Beak": (0.90, 0.72, 0.30),
                                    "Claws": (0.28, 0.24, 0.30)}),
    "quadruped": (VOL2 + "Wolf.blend", "Bone.003", 1.45,
                  lambda c, dark, lite: {"Wolf": c}),
    "mouse": (VOL2 + "Wolf.blend", "Bone.003", 0.85,
              lambda c, dark, lite: {"Wolf": c}),
    "kitty": (VOL2 + "Cat.blend", "Bone.003", 1.20,
              lambda c, dark, lite: {"Grey": c, "White": lite,
                                     "Pink": (0.95, 0.62, 0.66)}),
    "cow": (FARM + "Cow.blend", "Head", 1.5,
            lambda c, dark, lite: {"White": c, "Black": dark,
                                   "Pink": (0.95, 0.62, 0.66)}),
    "deer": (FARM + "Horse.blend", "Head", 1.55,
             lambda c, dark, lite: {"Material.003": c, "Material.006": dark}),

    "boar": (FARM + "Pig.blend", "Head", 1.30,
             lambda c, dark, lite: {"Material.003": dark, "Material": c}),
    "ghost": (CUTE + "Ghost.blend", "Head", 1.30,
              lambda c, dark, lite: {"Texture": c}),
    "human": (CUTE + "Alien_Tall.blend", "Head", 1.50,
              lambda c, dark, lite: {"Texture": c}),
    "blob": (MBASIC + "Slime.blend", "Head", 1.10,
             lambda c, dark, lite: {"Body": c, "Eyes": (0.09, 0.08, 0.14)}),
    "hedgehog": (CUTE + "Cactus.blend", "Head", 1.15,
                 lambda c, dark, lite: {"Texture": c}),
    "monkey": (CUTE + "Yeti.blend", "Head", 1.45,
               lambda c, dark, lite: {"Texture": c}),
    # a fish is long and low — 0.80 height-normalized it to a sliver
    # (audit-74 MED-2: tidscale's fix had to land here or 5 siblings stayed
    # static slivers)
    "serpent": (VOL2 + "Piranha.blend", "Bone", 1.35,
                lambda c, dark, lite: {"Brown": c, "LightYellow": lite,
                                       "Black": dark, "White": (0.92, 0.92, 0.88)}),
}

# bodies with no fitting source mesh stay on the primitive fallback path


def hex2rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))


def shade(c, f):
    return tuple(min(1.0, max(0.0, v * f)) for v in c)


def main():
    species = json.load(open(DUMP))
    out = ["# generated by mesh_map_gen.py — do not hand-edit", "CFG_EXT = {"]
    n = 0
    for d in species:
        sid = d.get("id", "")
        body = d.get("body", "")
        if sid in HAND or body not in TEMPLATES:
            continue
        blend, head_bone, th, mk = TEMPLATES[body]
        c = hex2rgb(d["color"])
        mats = mk(c, shade(c, 0.45), shade(c, 1.25))
        # deer on Horse.blend: rot 0 posed every deer rear-to-camera with
        # the head low — the same hump dozantler had (audit-74 MED-2)
        # Piranha faces +Y: rot -90 was head-ON to the camera (the blob the
        # audit saw); rot 0 is the clean side profile, head left like the
        # quadrupeds (audit-74 MED-2 probe over 5 rotations)
        rot = {"bird": 90.0, "serpent": 0.0, "deer": 90.0,
               "human": 35.0, "monkey": 35.0}.get(body, 0.0)
        action = {"blob": "Slime_Idle", "serpent": "Swimming"}.get(body, "Idle")
        # Idle(5,25) is the quiet window that fits most rigs; Swimming's
        # glide and the Horse graze need their own windows (audit-74)
        frames = {"serpent": (10, 30), "deer": (20, 80)}.get(body, (5, 25))
        mats_s = "{" + ", ".join(
            '"%s": (%.3f, %.3f, %.3f)' % (k, *v) for k, v in mats.items()) + "}"
        nose = ('"nose_r": 0.045, "nose_up": 0.02, ' if body in
                ("quadruped", "kitty", "cow", "deer", "boar", "mouse") else '')
        no_eyes = ', "no_eyes": True' if body == "blob" else ''
        # body marks stack UNDER per-sid marks as a space-separated
        # composite — every Piranha needs fins AND a legendary fish still
        # gets its crown (audit-75 LOW-1: single-slot dropped the fins)
        acc = " ".join(x for x in (
            {"serpent": "fins"}.get(body),
            rig_auto.ACCESSORY.get(sid)) if x)
        # name-semantic marks for unmarked species (S127 richness pass) —
        # the name literally calls for the part: plume->crest, mane->horns…
        if not acc:
            if body == "bird":
                acc = "crest" # every unmarked bird gets the head plume
            elif body in ("quadruped", "kitty", "deer", "cow") and \
                    any(k in sid for k in ("hoof", "mane", "antler", "fang")):
                acc = "horns"
            elif body == "ghost" and any(k in sid for k in ("wisp", "haunt")):
                acc = "halo"
            elif body == "human" and any(k in sid for k in ("grim", "shade")):
                acc = "mask"
        acc_s = ', "accessory": "%s"' % acc if acc else ''
        # S127 surface richness: displace where the body is textured for real
        # — fur/feather/hide reads through the cel pass; slime stays slick,
        # hedgehog quills and pact armor keep their manufactured surface
        disp = {"quadruped": 0.07, "kitty": 0.06, "cow": 0.05, "deer": 0.05,
                "boar": 0.05, "monkey": 0.08, "bird": 0.05, "ghost": 0.06,
                "serpent": 0.04}.get(body)
        disp_s = ('None' if disp is None else
                  '{"scale": 0.15, "strength": %.2f, "detail": 3.0}' % disp)
        subd = 3 if disp is not None else 2
        # head-bone tail = muzzle tip on quadrupeds (eyes trail it: fwd<0),
        # but skull top on upright/round rigs (eyes drop below + face -Y:
        # fwd>0, up<0)
        eye_fwd, eye_up = {
            "human": (0.06, -0.14), "ghost": (0.06, -0.10),
            "monkey": (0.06, -0.12), "hedgehog": (0.06, -0.10),
            # serpent eyes: at side profile fwd 0.10 floated them past the
            # snout; 0.05 seats them on the head silhouette (audit-74).
            # bird eyes: the Bone.005 tail is far down the neck, so the
            # default -0.12 trail dumped the eyes off the head entirely —
            # -1.15 climbs the bone back onto the skull (S127 A/B probe).
            # The literal saturates the renderer's xy-clamp (0.6*span ≈0.35):
            # anything ≤-0.58 lands identically — read it as "max backward"
            "serpent": (0.05, 0.06), "deer": (-0.14, 0.10), "bird": (-1.15, 0.12),
        }.get(body, (-0.12, 0.10))
        entry = (f'    "{sid}": {{"blend": "{blend}", "mat_map": {mats_s}, {nose}\n'
                 f'        "head_bone": "{head_bone}", "rot_z": {rot},\n'
                 f'        "action": "{action}", "frames": {frames},\n'
                 f'        "eye_r": 0.05, "eye_gap": 0.11, '
                 f'"eye_fwd": {eye_fwd}, "eye_up": {eye_up}, "target_h": {th},\n'
                 f'        "subd_wool": {subd}, "displace": {disp_s}{no_eyes}{acc_s}}},')
        out.append(entry)
        n += 1
    out.append("}")
    open(OUT, "w").write("\n".join(out) + "\n")
    print("wrote %d entries -> %s" % (n, OUT))


if __name__ == "__main__":
    main()
